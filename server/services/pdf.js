// PDF documents for guest-facing bills.
//
// The built-in Helvetica fonts use WinAnsi encoding, which does not contain the
// Indian rupee sign. Documents therefore use the unambiguous "Rs." prefix.

const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const PAGE_MARGIN = 40;
const CONTENT_WIDTH = 515;
const TABLE_COLUMNS = [
  { key: 'description', label: 'Description', width: 175, align: 'left' },
  { key: 'hsn', label: 'HSN/SAC', width: 55, align: 'left' },
  { key: 'quantity', label: 'Qty', width: 35, align: 'right' },
  { key: 'rate', label: 'Rate', width: 60, align: 'right' },
  { key: 'tax_rate', label: 'GST %', width: 40, align: 'right' },
  { key: 'tax', label: 'Tax', width: 60, align: 'right' },
  { key: 'amount', label: 'Amount', width: 90, align: 'right' }
];

function text(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/\u20b9/g, 'Rs. ');
}

function money(value) {
  return `Rs. ${(Number(value) || 0).toFixed(2)}`;
}

function dateOnly(value) {
  if (!value) return new Date().toISOString().slice(0, 10);
  return String(value).slice(0, 10);
}

function tableRows(items, isRestaurant = false) {
  return (items || []).map((item) => {
    const quantity = Number(item.quantity) || 1;
    const rate = Number(item.unit_price) || 0;
    const taxAmount = Number(item.tax_amount) || 0;
    const total = item.total_amount !== undefined
      ? Number(item.total_amount) || 0
      : quantity * rate + taxAmount;
    return {
      description: text(item.description || item.item_name || 'Item'),
      hsn: text(item.hsn_sac || (isRestaurant ? '996331' : (item.department === 'restaurant' || item.department === 'room_service' ? '996331' : '996311'))),
      quantity: String(quantity),
      rate: money(rate),
      tax_rate: `${Number(item.tax_rate) || 0}%`,
      tax: money(taxAmount),
      amount: money(total)
    };
  });
}

function drawRule(doc, y) {
  doc.moveTo(PAGE_MARGIN, y).lineTo(PAGE_MARGIN + CONTENT_WIDTH, y).lineWidth(0.6).strokeColor('#cbd5e1').stroke();
}

function drawTableHeader(doc, y) {
  doc.rect(PAGE_MARGIN, y, CONTENT_WIDTH, 20).fill('#f1f5f9');
  let x = PAGE_MARGIN;
  doc.fillColor('#475569').font('Helvetica-Bold').fontSize(7);
  for (const column of TABLE_COLUMNS) {
    doc.text(column.label, x + 4, y + 6, { width: column.width - 8, align: column.align });
    x += column.width;
  }
  return y + 20;
}

function drawItemRow(doc, row, y, isLast = false) {
  let x = PAGE_MARGIN;
  const descriptionHeight = doc.font('Helvetica').fontSize(8)
    .heightOfString(row.description, { width: TABLE_COLUMNS[0].width - 8 });
  const rowHeight = Math.max(20, descriptionHeight + 8);

  doc.fillColor('#0f172a').font('Helvetica').fontSize(8);
  for (const column of TABLE_COLUMNS) {
    doc.text(row[column.key], x + 4, y + 5, {
      width: column.width - 8,
      align: column.align,
      lineBreak: column.key === 'description'
    });
    x += column.width;
  }
  if (!isLast) drawRule(doc, y + rowHeight);
  return y + rowHeight;
}

function drawMetaBlock(doc, entries, x, y, width = 215) {
  doc.font('Helvetica').fontSize(8);
  let cursor = y;
  for (const [label, value] of entries) {
    if (!value) continue;
    doc.fillColor('#64748b').text(`${label}:`, x, cursor, { width: 70, continued: false });
    doc.fillColor('#0f172a').text(text(value), x + 70, cursor, { width: width - 70 });
    cursor += 13;
  }
  return cursor;
}

// Resolves a stored logo_url ('/uploads/...' or '/logo.png') to a readable file.
function resolveLogoPath(logoUrl) {
  if (!logoUrl) return null;
  const raw = String(logoUrl);
  const candidates = [];
  if (path.isAbsolute(raw)) candidates.push(raw);
  const relative = raw.replace(/^[/\\]+/, '');
  candidates.push(path.join(ROOT, 'data', relative));
  candidates.push(path.join(ROOT, 'public', relative));
  for (const candidate of candidates) {
    try {
      if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
    } catch (err) {
      // Ignore unreadable logo candidates and fall back to text branding.
    }
  }
  return null;
}

function newDocument() {
  return new PDFDocument({
    size: 'A4',
    bufferPages: true,
    margins: { top: PAGE_MARGIN, bottom: PAGE_MARGIN, left: PAGE_MARGIN, right: PAGE_MARGIN },
    info: { Creator: 'Nexuzy PMS', Producer: 'Nexuzy PMS' }
  });
}

const APP_FOOTER = 'Generated by Nexuzy PMS · Nexuzy Lab · nexuzy.in';

// Application branding belongs on every page of every bill, while the hotel's
// own logo remains the primary header branding. Stamping after the content is
// built keeps the footer out of the way and guarantees it on multi-page bills.
function stampPdfFooters(doc) {
  const range = doc.bufferedPageRange();
  for (let index = 0; index < range.count; index += 1) {
    doc.switchToPage(range.start + index);
    const bottom = doc.page.height - 52;
    doc.moveTo(PAGE_MARGIN, bottom - 8)
      .lineTo(PAGE_MARGIN + CONTENT_WIDTH, bottom - 8)
      .lineWidth(0.4)
      .strokeColor('#e2e8f0')
      .stroke();
    doc.font('Helvetica').fontSize(7).fillColor('#94a3b8')
      .text(APP_FOOTER, PAGE_MARGIN, bottom, { width: CONTENT_WIDTH - 80, align: 'left' })
      .text(`Page ${index + 1} of ${range.count}`, PAGE_MARGIN + CONTENT_WIDTH - 80, bottom, { width: 80, align: 'right' });
  }
}

function buildInvoiceDocument(doc, invoice) {
  const property = invoice.property || {};
  const customer = invoice.customer || {};
  const title = invoice.document_label || 'TAX INVOICE';
  let y = PAGE_MARGIN;
  let textX = PAGE_MARGIN;

  // Hotel branding uploaded in Settings is printed on every guest document.
  const logo = invoice.logo_path || resolveLogoPath(property.logo_url);
  if (logo) {
    try {
      doc.image(logo, PAGE_MARGIN, y, { fit: [42, 42] });
      textX = PAGE_MARGIN + 50;
    } catch (err) {
      textX = PAGE_MARGIN;
    }
  }
  const headerWidth = 310 - (textX - PAGE_MARGIN);

  doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(18)
    .text(text(property.name || 'Hotel'), textX, y, { width: headerWidth });
  y += 24;
  doc.font('Helvetica').fontSize(8).fillColor('#475569');
  const address = [property.address, property.city, property.state].filter(Boolean).join(', ');
  if (address) { doc.text(text(address), textX, y, { width: headerWidth }); y += 12; }
  if (property.phone || property.email) {
    doc.text(text([property.phone && `Phone: ${property.phone}`, property.email && `Email: ${property.email}`].filter(Boolean).join('  |  ')), textX, y, { width: headerWidth });
    y += 12;
  }
  doc.font('Helvetica-Bold').fillColor('#334155')
    .text(`GSTIN: ${text(property.gstin || 'Unregistered / Exempt')}`, textX, y, { width: headerWidth });

  doc.roundedRect(PAGE_MARGIN + 350, PAGE_MARGIN, 165, 24, 4).fill('#eef2ff');
  doc.fillColor('#4338ca').font('Helvetica-Bold').fontSize(10)
    .text(title.toUpperCase(), PAGE_MARGIN + 350, PAGE_MARGIN + 7, { width: 165, align: 'center' });
  doc.fillColor('#475569').font('Helvetica').fontSize(8)
    .text(`Number: ${text(invoice.invoice_number || invoice.bill_number || invoice.order_number || '—')}`, PAGE_MARGIN + 350, PAGE_MARGIN + 32, { width: 165, align: 'right' })
    .text(`Date: ${dateOnly(invoice.date || invoice.settled_at)}`, PAGE_MARGIN + 350, PAGE_MARGIN + 44, { width: 165, align: 'right' });

  y = Math.max(y + 24, PAGE_MARGIN + 62);
  drawRule(doc, y);
  y += 12;

  doc.fillColor('#64748b').font('Helvetica-Bold').fontSize(7).text('BILLED TO', PAGE_MARGIN, y);
  doc.fillColor('#0f172a').font('Helvetica-Bold').fontSize(11)
    .text(text(customer.name || 'Guest'), PAGE_MARGIN, y + 11, { width: 280 });
  let customerY = y + 26;
  doc.font('Helvetica').fontSize(8).fillColor('#475569');
  if (customer.company) { doc.text(text(customer.company), PAGE_MARGIN, customerY, { width: 280 }); customerY += 11; }
  if (customer.gstin) { doc.text(`GSTIN: ${text(customer.gstin)}`, PAGE_MARGIN, customerY, { width: 280 }); customerY += 11; }
  if (customer.phone) { doc.text(`Phone: ${text(customer.phone)}`, PAGE_MARGIN, customerY, { width: 280 }); }

  const meta = [];
  if (invoice.folio_number) meta.push(['Folio', invoice.folio_number]);
  if (invoice.stay_number) meta.push(['Stay', invoice.stay_number]);
  if (invoice.order_number) meta.push(['Order', invoice.order_number]);
  if (invoice.table_number) meta.push(['Table', invoice.table_number]);
  if (invoice.room_number) meta.push(['Room', invoice.room_number]);
  if (invoice.payment_method) meta.push(['Payment', String(invoice.payment_method).replace(/_/g, ' ')]);
  drawMetaBlock(doc, meta, PAGE_MARGIN + 300, y, 215);

  y = Math.max(customerY + 8, y + 60);
  y = drawTableHeader(doc, y);
  const rows = tableRows(invoice.items, Boolean(invoice.is_restaurant_bill));

  for (let index = 0; index < rows.length; index += 1) {
    if (y > doc.page.height - 90) {
      doc.addPage();
      y = PAGE_MARGIN;
      y = drawTableHeader(doc, y);
    }
    y = drawItemRow(doc, rows[index], y, index === rows.length - 1);
  }

  if (!rows.length) {
    doc.fillColor('#64748b').font('Helvetica-Oblique').fontSize(8)
      .text('No charge lines on this document.', PAGE_MARGIN, y + 8, { width: CONTENT_WIDTH, align: 'center' });
    y += 28;
  }

  if (y > doc.page.height - 180) {
    doc.addPage();
    y = PAGE_MARGIN;
  }

  const totalsX = PAGE_MARGIN + 300;
  const totalsWidth = CONTENT_WIDTH - 300;
  const subtotal = invoice.subtotal !== undefined ? invoice.subtotal : 0;
  const tax = invoice.total_tax !== undefined ? invoice.total_tax : (Number(invoice.cgst || 0) + Number(invoice.sgst || 0));
  const grand = invoice.grand_total !== undefined ? invoice.grand_total : invoice.total_amount;
  const paid = invoice.paid_amount;
  const balance = invoice.balance_due !== undefined ? invoice.balance_due : (Number(grand) - Number(paid || 0));

  y += 10;
  const totalLine = (label, value, bold = false) => {
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(bold ? 10 : 8)
      .fillColor(bold ? '#0f172a' : '#475569')
      .text(label, totalsX, y, { width: totalsWidth / 2, align: 'left' });
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(bold ? 10 : 8)
      .fillColor(bold ? '#4338ca' : '#0f172a')
      .text(money(value), totalsX + totalsWidth / 2, y, { width: totalsWidth / 2, align: 'right' });
    y += bold ? 17 : 14;
  };
  totalLine('Taxable Value', subtotal);
  if (invoice.is_tax_invoice) {
    totalLine('CGST', invoice.cgst || 0);
    totalLine('SGST', invoice.sgst || 0);
  } else {
    totalLine('GST', tax);
  }
  drawRule(doc, y + 1);
  y += 7;
  totalLine('Grand Total', grand, true);
  if (paid !== undefined) totalLine('Amount Paid', paid);
  if (invoice.is_tax_invoice) totalLine('Balance Due', balance, true);

  const detailsY = y + 8;
  doc.fillColor('#64748b').font('Helvetica-Bold').fontSize(7)
    .text('PAYMENT DETAILS', PAGE_MARGIN, detailsY);
  doc.font('Helvetica').fontSize(8).fillColor('#334155');
  const bankLines = [
    property.bank_name ? `Bank: ${property.bank_name}` : null,
    property.bank_account_number ? `A/C: ${property.bank_account_number}` : null,
    property.bank_ifsc ? `IFSC: ${property.bank_ifsc}` : null,
    property.upi_id ? `UPI: ${property.upi_id}` : null
  ].filter(Boolean);
  if (bankLines.length) {
    doc.text(bankLines.join('\n'), PAGE_MARGIN, detailsY + 11, { width: 270, lineGap: 2 });
    y = Math.max(y, detailsY + 11 + bankLines.length * 11);
  } else {
    y = Math.max(y, detailsY + 11);
  }

  if (invoice.disclaimer) {
    doc.fillColor('#64748b').font('Helvetica-Oblique').fontSize(7)
      .text(text(invoice.disclaimer), PAGE_MARGIN, y + 14, { width: CONTENT_WIDTH - 140 });
  }
  doc.fillColor('#475569').font('Helvetica').fontSize(7)
    .text('Computer generated document. Valid without a physical signature.', PAGE_MARGIN, y + 34, { width: CONTENT_WIDTH - 140 });

  doc.moveTo(PAGE_MARGIN + CONTENT_WIDTH - 130, y + 26).lineTo(PAGE_MARGIN + CONTENT_WIDTH, y + 26).lineWidth(0.5).strokeColor('#94a3b8').stroke();
  doc.fillColor('#64748b').fontSize(7).text('Authorised Signatory', PAGE_MARGIN + CONTENT_WIDTH - 130, y + 31, { width: 130, align: 'center' });
}

function generateInvoicePdf(invoice) {
  return new Promise((resolve, reject) => {
    const doc = newDocument();
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    try {
      buildInvoiceDocument(doc, invoice);
      stampPdfFooters(doc);
      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

async function sendInvoicePdf(res, invoice, filename) {
  const buffer = await generateInvoicePdf(invoice);
  const safeName = String(filename || `invoice-${invoice.invoice_number || 'document'}.pdf`).replace(/[^a-zA-Z0-9._-]/g, '-');
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${safeName}"`);
  res.setHeader('Cache-Control', 'no-store');
  res.setHeader('Content-Length', buffer.length);
  res.end(buffer);
}

module.exports = {
  generateInvoicePdf,
  sendInvoicePdf,
  resolveLogoPath,
  money,
  text
};
